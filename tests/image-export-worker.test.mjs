import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { MemoryDirectory } from './helpers/opfs.mjs';

test('worker downloads repeated blobs once and preserves manifest layer references', async t => {
  const root = new MemoryDirectory();
  const jobs = await root.getDirectoryHandle('dockerboost-downloads', { create: true });
  await jobs.getDirectoryHandle('image-test', { create: true });
  const storage = Object.getOwnPropertyDescriptor(navigator, 'storage');
  Object.defineProperty(navigator, 'storage', { configurable: true, value: { getDirectory: async () => root } });
  const oldSelf = globalThis.self;
  let handler, finish;
  const result = new Promise(resolve => { finish = resolve; });
  const events = [];
  globalThis.self = { addEventListener(_type, callback) { handler = callback; }, postMessage(message) { events.push(message); if ('ok' in message) finish(message); } };
  t.after(() => { if (storage) Object.defineProperty(navigator, 'storage', storage); else delete navigator.storage; if (oldSelf === undefined) delete globalThis.self; else globalThis.self = oldSelf; });
  const digest = text => `sha256:${createHash('sha256').update(text).digest('hex')}`;
  let configText = JSON.stringify({ os: 'linux', architecture: 'amd64' });
  const config = { digest: digest(configText), size: Buffer.byteLength(configText) };
  const layer = { digest: digest('abc'), size: 3 };
  const manifest = { schemaVersion: 2, mediaType: 'application/vnd.oci.image.manifest.v1+json', config, layers: [layer, layer] };
  const requests = [];
  let indexMode = false, exact, variant, variantText, tamper = false;
  t.mock.method(globalThis, 'fetch', async url => {
    requests.push(url);
    if (indexMode && url.includes('/manifests/latest')) return Response.json({ manifests: [
      { digest: variant, platform: { os: 'linux', architecture: 'amd64', variant: 'v2' } },
      { digest: exact, platform: { os: 'linux', architecture: 'amd64' } }
    ] });
    const body = tamper ? JSON.stringify({ ...manifest, annotations: { modified: 'true' } }) : indexMode && url.includes(`/manifests/${variant}`) ? variantText : JSON.stringify(manifest, null, 2);
    return url.includes('/manifests/') ? new Response(body, { headers: { 'Content-Type': 'application/json' } }) : new Response(url.includes(config.digest) ? configText : 'abc');
  });
  await import('../src/client/features/download/image-export-worker.js');
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  const completed = await result;
  assert.equal(completed.ok, true, completed.error);
  assert.equal(requests.filter(url => url.includes('/blobs/')).length, 2);
  assert.ok(events.filter(event => event.phase === 'download').every(event => event.total === config.size + 3 && event.completed <= config.size + 3));
  const archive = Buffer.from(await completed.result.archive.arrayBuffer());
  const list = spawnSync('tar', ['-tf', '-'], { input: archive });
  assert.equal(list.status, 0);
  assert.equal(list.stdout.toString().split('\n').filter(name => name === `blobs/sha256/${layer.digest.slice(7)}`).length, 1);
  const output = spawnSync('tar', ['-xOf', '-', 'manifest.json'], { input: archive });
  assert.deepEqual(JSON.parse(output.stdout)[0].Layers, [`blobs/sha256/${layer.digest.slice(7)}`, `blobs/sha256/${layer.digest.slice(7)}`]);
  const rawManifest = JSON.stringify(manifest, null, 2);
  const preserved = spawnSync('tar', ['-xOf', '-', `blobs/sha256/${digest(rawManifest).slice(7)}`], { input: archive });
  assert.equal(preserved.stdout.toString(), rawManifest);
  const failure = new Promise(resolve => { finish = resolve; });
  manifest.layers = [layer, { ...layer, size: 4 }];
  requests.length = 0;
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  const rejected = await failure;
  assert.equal(rejected.ok, false);
  assert.match(rejected.error, /相同 digest.*大小不一致/);
  assert.equal(requests.filter(url => url.includes('/blobs/')).length, 0);
  const corrupt = new Promise(resolve => { finish = resolve; });
  manifest.layers = [{ ...layer, digest: digest('bad') }]; requests.length = 0;
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  const mismatch = await corrupt;
  assert.equal(mismatch.ok, false);
  assert.match(mismatch.error, /digest 校验失败/);
  for (const invalid of [{ ...layer, digest: 'sha512:abc' }, { ...layer, size: -1 }, { ...layer, size: 1.5 }]) {
    const next = new Promise(resolve => { finish = resolve; });
    manifest.layers = [invalid]; requests.length = 0;
    handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
    const error = await next;
    assert.equal(error.ok, false);
    assert.match(error.error, /digest|大小无效/);
    assert.equal(requests.filter(url => url.includes('/blobs/')).length, 0);
  }
  const selected = new Promise(resolve => { finish = resolve; });
  manifest.layers = [layer]; indexMode = true; requests.length = 0;
  exact = digest(JSON.stringify(manifest, null, 2));
  variantText = JSON.stringify({ ...manifest, annotations: { fixture: 'variant' } }, null, 2);
  variant = digest(variantText);
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.equal((await selected).ok, true);
  assert.ok(requests.some(url => url.includes(`/manifests/${exact}`)));
  assert.ok(!requests.some(url => url.includes(`/manifests/${variant}`)));
  const indexedVariant = new Promise(resolve => { finish = resolve; });
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64/v2', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.equal((await indexedVariant).ok, true, 'index variant may be absent from the config');
  tamper = true;
  const changedManifest = new Promise(resolve => { finish = resolve; });
  requests.length = 0;
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.match((await changedManifest).error, /清单 digest 校验失败/);
  assert.equal(requests.filter(url => url.includes('/blobs/')).length, 0);
  tamper = false;
  indexMode = false;
  const directDigest = digest(JSON.stringify(manifest, null, 2));
  const direct = new Promise(resolve => { finish = resolve; });
  handler({ data: { repository: 'library/nginx', reference: directDigest, repoTag: `nginx@${directDigest}`, source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.equal((await direct).ok, true);
  const sha512 = `sha512:${createHash('sha512').update(JSON.stringify(manifest, null, 2)).digest('hex')}`;
  const sha384 = `sha384:${createHash('sha384').update(JSON.stringify(manifest, null, 2)).digest('hex')}`;
  const direct384 = new Promise(resolve => { finish = resolve; });
  handler({ data: { repository: 'library/nginx', reference: sha384, repoTag: `nginx@${sha384}`, source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.equal((await direct384).ok, true);
  const direct512 = new Promise(resolve => { finish = resolve; });
  handler({ data: { repository: 'library/nginx', reference: sha512, repoTag: `nginx@${sha512}`, source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.equal((await direct512).ok, true);
  tamper = true;
  const changed512 = new Promise(resolve => { finish = resolve; });
  requests.length = 0;
  handler({ data: { repository: 'library/nginx', reference: sha512, repoTag: `nginx@${sha512}`, source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.match((await changed512).error, /清单 digest 校验失败/);
  assert.equal(requests.filter(url => url.includes('/blobs/')).length, 0);
  tamper = false;
  const unsupported = new Promise(resolve => { finish = resolve; });
  handler({ data: { repository: 'library/nginx', reference: 'other:1234', repoTag: 'nginx@other:1234', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.match((await unsupported).error, /不支持或无效的镜像清单 digest/);
  tamper = true;
  const changedDirect = new Promise(resolve => { finish = resolve; });
  requests.length = 0;
  handler({ data: { repository: 'library/nginx', reference: directDigest, repoTag: `nginx@${directDigest}`, source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.match((await changedDirect).error, /清单 digest 校验失败/);
  assert.equal(requests.filter(url => url.includes('/blobs/')).length, 0);
  tamper = false;
  const missingVariant = new Promise(resolve => { finish = resolve; });
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64/v2', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  assert.match((await missingVariant).error, /镜像架构.*不匹配/);
  configText = JSON.stringify({ os: 'linux', architecture: 'arm64' });
  config.digest = digest(configText); config.size = Buffer.byteLength(configText);
  const changed = new Promise(resolve => { finish = resolve; });
  requests.length = 0;
  handler({ data: { repository: 'library/nginx', reference: 'latest', repoTag: 'nginx:latest', source: 'auto', platform: 'linux/amd64', filename: 'image.tar', version: 'test', sessionId: 'image-test' } });
  const changedResult = await changed;
  assert.equal(changedResult.ok, false);
  assert.match(changedResult.error, /镜像架构.*不匹配/);
  assert.equal(changedResult.retryable, false);
  assert.equal(changedResult.code, 'PLATFORM_CHANGED');
  assert.equal(requests.filter(url => url.includes('/blobs/')).length, 1, 'mismatch stops before downloading layers');
});
